import type { Layer } from "./layer.js";
import type { State } from "./state.js";
import type { Preset } from "./preset.js";
import type { Variable } from "./variable.js";
import type { Asset } from "./asset.js";
import type { Timeline } from "./timeline.js";
import type { SlideRef } from "./slides.js";
import type { AtelierDesign } from "./design.js";

/** Canvas configuration */
export interface Canvas {
  width: number;
  height: number;
  fps: number;
  /** Background color (optional) */
  background?: string;
}

/**
 * Project kind — determines which fields are meaningful and how exporters
 * compose the output.
 *
 * - **video**: a timeline-based composition with clip layers, optional
 *   `timeline` summary, optional multi-track structure via Group layers.
 *   This is the default for backcompat: a document with no `kind` field is
 *   treated as a video project.
 * - **image**: a static composition rendered at a single frame. States and
 *   deltas are ignored by the image exporter; canvas + layers + design is
 *   the surface.
 * - **carousel**: a manifest of ordered `slides` (refs to other `.atelier`
 *   files). The carousel doc has no layers/states of its own; the exporter
 *   stitches each slide's render into a sequence with transitions.
 */
export type ProjectKind = "video" | "image" | "carousel";

/** The root animation document */
export interface AtelierDocument {
  /** Format version */
  version: string;
  /** Animation name */
  name: string;
  /**
   * Project kind. Absent = "video" for backcompat with pre-v1 documents.
   */
  kind?: ProjectKind;
  description?: string;
  tags?: string[];
  canvas: Canvas;
  /**
   * Per-file design / brand block. Self-contained — readers do NOT merge
   * this with the workspace DESIGN. See `AtelierDesign` for lineage
   * semantics (relatedTo[]).
   */
  design?: AtelierDesign;
  variables?: Record<string, Variable>;
  assets?: Record<string, Asset>;
  presets?: Record<string, Preset>;
  layers: Layer[];
  states: Record<string, State>;
  /**
   * Derived clip-placement overview for video-kind projects (regenerated by
   * writers; readers tolerate absent/stale). See `Timeline` for semantics.
   */
  timeline?: Timeline;
  /**
   * Carousel slides — only meaningful when `kind === "carousel"`. Each ref
   * points at any `.atelier` file in the workspace. See `SlideRef` for
   * cycle-safety semantics.
   */
  slides?: SlideRef[];
}
